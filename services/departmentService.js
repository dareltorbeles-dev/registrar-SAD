const db = require("../db");
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

const getDepartment = (callback) => {

    const sql = `SELECT * FROM department`;

    db.query (sql, callback) 
}
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

const postDepartment = (department, callback) => {
    const sql = `INSERT INTO department (department_name)
    VALUES (?)
    `;

    db.query(
        sql,
        [
            department.department_name
        ],
        callback
    )
}
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////



module.exports = {
    getDepartment,
    postDepartment
}